"""Textes de l'interface, dans la langue choisie dans COGBox.

COGBox enregistre son choix dans CogBox.ini : `[Launcher] Language = fr` (codes du launcher :
en, es, fr, de, it, pt-BR, pl, hu, ru, ja, zh-Hans, ko, ou `auto`). Ici on couvre en, fr, pt,
zh, ko, pl, ru, cs, hu ; tout code absent, inconnu ou vide retombe sur l'anglais.

Les traductions sont faites à la machine, comme celles de COGBox : les corrections sont
bienvenues. Pour en ajouter une, recopier une table de LANG_TEXT (les clés doivent être
identiques ; --selftest le vérifie).
"""

import os

LANGS = ("en", "fr", "pt", "zh", "ko", "pl", "ru", "cs", "hu")
FALLBACK = "en"

# Codes du launcher -> code d'ici.
ALIASES = {
    "pt-br": "pt",
    "pt_br": "pt",
    "pt": "pt",
    "zh-hans": "zh",
    "zh-hant": "zh",
    "zh_cn": "zh",
    "zh": "zh",
}

_code = FALLBACK


def code():
    """Code courant (toujours l'un de LANGS)."""
    return _code


def set_language(value):
    """Fixe la langue depuis un code ou une valeur de CogBox.ini ; renvoie le code retenu."""
    global _code
    _code = normalize(value)
    return _code


def normalize(value):
    """Valeur de CogBox.ini -> code d'ici (anglais si inconnu)."""
    raw = (value or "").strip().lower()
    if not raw or raw == "auto":
        return system_language()
    raw = ALIASES.get(raw, raw)
    return raw if raw in LANGS else FALLBACK


def system_language():
    """Langue de Windows, comme i18n_auto_code() de COGBox (anglais hors Windows)."""
    if os.name != "nt":
        return FALLBACK
    try:
        import ctypes

        langid = ctypes.windll.kernel32.GetUserDefaultUILanguage()
    except Exception:
        return FALLBACK
    primary = langid & 0x3FF
    return {0x09: "en", 0x0C: "fr", 0x16: "pt", 0x04: "zh", 0x12: "ko",
            0x15: "pl", 0x19: "ru", 0x05: "cs", 0x0E: "hu"}.get(primary, FALLBACK)


def t(key, /, **values):
    """Texte de la clé dans la langue courante, repli sur l'anglais."""
    table = LANG_TEXT.get(_code, {})
    text = table.get(key) or LANG_TEXT[FALLBACK].get(key)
    if text is None:
        return key
    return text.format(**values) if values else text


def missing():
    """Clés absentes d'une langue (vérifié par --selftest)."""
    base = set(LANG_TEXT[FALLBACK])
    return {lang: sorted(base - set(LANG_TEXT.get(lang, {}))) for lang in LANGS
            if base - set(LANG_TEXT.get(lang, {}))}


